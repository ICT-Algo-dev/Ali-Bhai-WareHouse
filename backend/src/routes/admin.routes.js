import { Router } from 'express';
import { deleteInquiry, listInquiries, login, updateInquiryStatus } from '../controllers/admin.controller.js';
import { requireAdmin } from '../middleware/auth.js';
import { deleteAdminIntakeFile, deleteIntake, downloadIntakeFile, downloadIntakeFilesZip, getIntake, getIntakePdf, listIntakes, updateIntakeStatus, updateProductVerification } from '../controllers/admin-intake.controller.js';
const router = Router();
router.post('/login', login);
router.use(requireAdmin);
router.get('/inquiries', listInquiries);
router.patch('/inquiries/:id/status', updateInquiryStatus);
router.delete('/inquiries/:id', deleteInquiry);
router.get('/intakes', listIntakes);
router.get('/intakes/:id', getIntake);
router.get('/intakes/:id/pdf', getIntakePdf);
router.get('/intakes/:id/files.zip', downloadIntakeFilesZip);
router.get('/intakes/:id/files/:fileId', downloadIntakeFile);
router.delete('/intakes/:id/files/:fileId', deleteAdminIntakeFile);
router.patch('/intakes/:id/status', updateIntakeStatus);
router.patch('/intakes/:id/products/:productId/verification', updateProductVerification);
router.delete('/intakes/:id', deleteIntake);
export default router;
